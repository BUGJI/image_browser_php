/**
 * 生成图标 SVG 字符串
 * @param {string} name  ICONS 中的键
 * @param {number} size  像素尺寸
 * @param {string} className 额外 class
 */
export function icon(name, size = 18, className = '') {
  const body = ICONS[name] || '';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="icon-svg${className ? ' ' + className : ''}" aria-hidden="true">${body}</svg>`;
}

/** 把页面里带 data-icon 的元素填充为图标 */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    const name = el.dataset.icon;
    const size = parseInt(el.dataset.iconSize || '16', 10);
    if (ICONS[name]) el.innerHTML = icon(name, size);
  });
}
